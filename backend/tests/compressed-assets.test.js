import express from 'express';
import request from 'supertest';
import { gzipSync } from 'node:zlib';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { afterEach, expect, it } from 'vitest';
const require=createRequire(import.meta.url);
const { compressedAssets }=require('../src/compressedAssets');
let root;
afterEach(()=>{if(root)rmSync(root,{recursive:true,force:true});});
it('serves the same viewer script compressed and falls back to the original when needed',async()=>{
  root=mkdtempSync(path.join(tmpdir(),'compressed-assets-'));
  const text='const worker = "PDF viewer";\n'.repeat(1000),compressed=gzipSync(text);
  writeFileSync(path.join(root,'worker-hash.mjs'),text);
  writeFileSync(path.join(root,'worker-hash.mjs.gz'),compressed);
  writeFileSync(path.join(root,'legacy.js'),'legacy');
  const app=express();app.use('/assets',compressedAssets(root),express.static(root));
  const gzip=await request(app).get('/assets/worker-hash.mjs').set('Accept-Encoding','gzip').expect(200);
  expect(gzip.headers['content-encoding']).toBe('gzip');
  expect(gzip.headers['content-type']).toMatch(/javascript/);
  expect(gzip.headers['content-length']).toBe(String(compressed.length));
  expect(gzip.headers.vary).toMatch(/Accept-Encoding/);
  expect(gzip.text).toBe(text);
  const plain=await request(app).get('/assets/worker-hash.mjs').set('Accept-Encoding','identity').expect(200);
  expect(plain.headers['content-encoding']).toBeUndefined();expect(plain.text).toBe(text);
  const fallback=await request(app).get('/assets/legacy.js').set('Accept-Encoding','gzip').expect(200);
  expect(fallback.headers['content-encoding']).toBeUndefined();expect(fallback.text).toBe('legacy');
});
